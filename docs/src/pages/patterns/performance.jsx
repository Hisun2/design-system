/** 뼈대가 0.3초에 걸쳐 사라지고 내용이 나타나는 모습. */
function FadeDemo() {
  const [loading, setLoading] = React.useState(false);
  const run = () => {
    setLoading(true);
    setTimeout(() => setLoading(false), 2000);
  };
  return (
    <Flex direction="column" gap={4} w={320}>
      <SpinContainer loading={loading} size="l" duration={300}>
        <Text tag="p" size={200} my={2}>가나다 상사 · 문서 12건</Text>
        <Text tag="p" size={200} my={2}>라마바 물산 · 문서 4건</Text>
        <Text tag="p" size={200} my={2}>사아자 유통 · 문서 27건</Text>
      </SpinContainer>
      <Flex>
        <Button onClick={run} disabled={loading}>다시 불러오기</Button>
      </Flex>
    </Flex>
  );
}

